"""Package a small static demo and a complete downloadable evidence archive."""

import argparse
import hashlib
import json
import shutil
import zipfile
from pathlib import Path

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("public", type=Path, help="Directory generated by the report phase")
parser.add_argument("destination", type=Path, help="Empty static-site checkout")
parser.add_argument("archive", type=Path, help="Destination .zip for all public evidence")
args = parser.parse_args()
source = args.public.resolve()
destination = args.destination.resolve()
if (
    source == destination
    or source in destination.parents
    or source in args.archive.resolve().parents
):
    raise SystemExit("Static destination must be separate from the source export")
data = json.loads((source / "results.json").read_text())
selected = {
    "index.html",
    "results.json",
    "results.csv",
    "report.md",
    "publication.json",
    "evidence/files.json",
}
for row in data["rows"]:
    selected.add(row["harness_diff"])
    selected.add(f"evidence/executions/{row['session']}/stored-spans.json")
    if row.get("judge_evidence"):
        selected.add(row["judge_evidence"])
    selected.update(output["path"] for output in row["outputs"])
for condition in data["unavailable_conditions"]:
    selected.add(condition["result"])
for path in (source / "media").rglob("*"):
    if path.is_file():
        selected.add(str(path.relative_to(source)))
for relative in sorted(selected):
    path = source / relative
    if path.is_symlink() or source not in path.resolve().parents:
        raise SystemExit("Unsafe public path: " + relative)
    if not path.exists():
        if relative == "publication.json":
            continue
        raise SystemExit("Missing public path: " + relative)
    target = destination / relative
    target.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(path, target)
(destination / ".nojekyll").touch()
args.archive.parent.mkdir(parents=True, exist_ok=True)
with zipfile.ZipFile(
    args.archive, "w", compression=zipfile.ZIP_DEFLATED, compresslevel=6
) as archive:
    for path in sorted(source.rglob("*")):
        if path.is_file() and not path.is_symlink():
            archive.write(path, path.relative_to(source))
digest = hashlib.sha256(args.archive.read_bytes()).hexdigest()
args.archive.with_suffix(".zip.sha256").write_text(f"{digest}  {args.archive.name}\n")
print(
    json.dumps(
        {
            "site": str(destination),
            "archive": str(args.archive),
            "sha256": digest,
            "site_files": len(selected),
        },
        indent=2,
    )
)
